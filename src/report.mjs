/** Render an analysis result as a shareable Markdown report. */

const ICON = { high: "●●●", medium: "●●○", low: "●○○" };

function fmtFrame(f) {
  const loc = f.file ? `${f.file}:${f.line}${f.column ? `:${f.column}` : ""}` : "(no location)";
  const tag = f.kind === "app" ? "app" : f.kind === "dependency" ? "dep" : f.kind;
  const mod = f.modified ? " **[locally modified]**" : "";
  return `- \`${f.fn ?? "<anonymous>"}\` — ${loc} _( ${tag}${f.repeats > 1 ? `, x${f.repeats}` : ""} )_${mod}`;
}

/**
 * @param {object[]} analyses
 * @param {{source:string, records:number, generatedAt?:string, toolVersion?:string}} meta
 */
export function renderMarkdown(analyses, meta) {
  const out = [];
  const total = analyses.reduce((n, a) => n + a.count, 0);
  const top = analyses[0];

  out.push(`# Crash analysis — ${meta.source}`);
  out.push("");
  out.push(
    `${meta.records} error record(s), ${analyses.length} distinct failure shape(s).` +
      (meta.environment ? ` Environment: ${meta.environment}.` : ""),
  );
  out.push("");

  if (top) {
    out.push("## Verdict");
    out.push("");
    out.push(`**Dominant failure:** \`${top.sample}\``);
    out.push("");
    out.push(`- Shape: ${top.gist}`);
    out.push(`- Occurrences: ${top.count} of ${total}`);
    out.push(`- Recurrence: ${top.recurrence.note}`);
    out.push(`- Analysis confidence: ${ICON[top.confidence.level]} ${top.confidence.level} (${top.confidence.reasons.join(", ") || "input is thin"})`);
    if (top.primaryFrame) {
      out.push(
        `- Primary suspect: \`${top.primaryFrame.fn ?? "<anonymous>"}\` at \`${top.primaryFrame.file}:${top.primaryFrame.line}\``,
      );
    }
    out.push("");
  }

  if (analyses.length > 1) {
    out.push("## Failure shapes");
    out.push("");
    out.push("| # | Occurrences | Shape | Message |");
    out.push("|---|---|---|---|");
    analyses.forEach((a, i) => {
      out.push(`| ${i + 1} | ${a.count} | ${a.gist} | \`${truncate(a.sample, 70)}\` |`);
    });
    out.push("");
  }

  analyses.forEach((a, i) => {
    out.push(`## ${i + 1}. ${a.gist}`);
    out.push("");
    out.push("```");
    out.push(a.sample);
    out.push("```");
    out.push("");
    out.push(`- Signature: \`${a.signature}\``);
    out.push(`- Occurrences: ${a.count}`);
    if (a.precondition) out.push(`- Spread: ${a.precondition.note}`);
    out.push(`- Confidence: ${a.confidence.level} (${a.confidence.score}/100)`);
    out.push("");

    if (a.rankedFrames.length) {
      out.push("### Where to look");
      out.push("");
      a.rankedFrames.forEach((f) => out.push(fmtFrame(f)));
      out.push("");
    }

    if (a.sourceContext) {
      out.push(`### Source — ${a.sourceContext.file}:${a.sourceContext.start}-${a.sourceContext.end}`);
      out.push("");
      out.push("```" + guessLang(a.sourceContext.file));
      for (const l of a.sourceContext.lines) out.push(`${l.hit ? ">" : " "} ${String(l.n).padStart(5)} | ${l.text}`);
      out.push("```");
      out.push("");
      if (a.localModification) {
        out.push(
          "> This file has a backup beside it, so it was edited after this log was written — the line numbers above may no longer match the crashing version.",
        );
        out.push("");
      }
    }

    if (a.localModification) {
      out.push("### Local modification detected");
      out.push("");
      out.push("At least one frame sits in a file that looks locally modified:");
      out.push("");
      for (const m of a.localModification) out.push(`- \`${m.file}\` (${m.signals.join(", ")})`);
      out.push("");
      out.push(
        "> A local patch changes the contract other code was written against. Before reading further, diff this file against its shipped version.",
      );
      out.push("");
    }

    if (a.hypotheses.length) {
      out.push("### Hypotheses (most likely first)");
      out.push("");
      a.hypotheses.forEach((h, k) => out.push(`${k + 1}. ${h}`));
      out.push("");
    }

    if (a.verify.length) {
      out.push("### How to confirm or kill each hypothesis");
      out.push("");
      a.verify.forEach((v) => out.push(`- ${v}`));
      out.push("");
    }
  });

  out.push("---");
  out.push("");
  out.push(
    `Generated by crashlens${meta.toolVersion ? ` v${meta.toolVersion}` : ""}${meta.generatedAt ? ` on ${meta.generatedAt}` : ""}. ` +
      "Deterministic analysis: every finding traces to a line in the input. Hypotheses are candidates, not verdicts.",
  );
  out.push("");
  return out.join("\n");
}

function truncate(s, n) {
  const t = s.replace(/\|/g, "\\|");
  return t.length > n ? `${t.slice(0, n - 1)}…` : t;
}

function guessLang(file) {
  if (/\.(ts|tsx)$/.test(file)) return "ts";
  if (/\.(js|mjs|cjs|jsx)$/.test(file)) return "js";
  if (/\.py$/.test(file)) return "py";
  if (/\.rs$/.test(file)) return "rust";
  if (/\.go$/.test(file)) return "go";
  return "";
}

/** Compact one-screen summary for terminals. */
export function renderSummary(analyses, meta) {
  const lines = [];
  const total = analyses.reduce((n, a) => n + a.count, 0);
  lines.push(`crashlens — ${meta.source}`);
  lines.push(`${meta.records} record(s) / ${analyses.length} shape(s)`);
  lines.push("");
  analyses.slice(0, 6).forEach((a, i) => {
    const pct = total ? Math.round((a.count / total) * 100) : 0;
    lines.push(`${i + 1}. [${String(a.count).padStart(3)}x ${String(pct).padStart(3)}%] ${a.sample}`);
    lines.push(`   ${a.gist}`);
    if (a.primaryFrame?.file) {
      lines.push(`   → ${a.primaryFrame.fn ?? "<anonymous>"} @ ${a.primaryFrame.file}:${a.primaryFrame.line}`);
    }
    if (a.localModification?.length) lines.push(`   ⚠ locally modified file in path`);
    lines.push(`   confidence: ${a.confidence.level}`);
    lines.push("");
  });
  if (analyses.length > 6) lines.push(`(+${analyses.length - 6} more shape(s) — use --json or --md for the full report)`);
  return lines.join("\n");
}